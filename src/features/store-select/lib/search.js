/** Слова, которые человек может набрать, но в адресе они записаны сокращённо или не важны для поиска */
const SKIP = new Set(['аникс', 'магазин', 'г', 'город', 'с', 'село', 'р', 'п', 'рп', 'поселок', 'ул', 'улица', 'пер', 'переулок', 'пр', 'т', 'проспект', 'пл', 'площадь', 'д', 'дом']);

/** К одному виду: строчные, ё → е, знаки препинания и кавычки — пробелы */
const normalize = (s) => s.toLowerCase().replace(/ё/g, 'е').replace(/[^a-zа-я0-9]+/g, ' ').trim();

/** Слова запроса без служебных; пустой список — показать все магазины */
export function queryWords(q) {
  return normalize(q).split(' ').filter((w) => w && !SKIP.has(w));
}

/**
 * Магазин подходит, если каждое слово запроса — начало какого-то слова в названии, адресе или районе.
 * Порядок слов любой: «Васильева 30», «Бийск Славянский», «славян», «Горно-Алтайск Ленина».
 */
export function matchStore(store, words) {
  if (!words.length) return true;
  const own = normalize(`${store.name} ${store.address} ${store.district ?? ''}`).split(' ');
  return words.every((w) => own.some((o) => o.startsWith(w)));
}
