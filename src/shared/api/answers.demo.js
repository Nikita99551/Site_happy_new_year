/** Предсказуемый генератор случайных чисел: у демо-ответов одни и те же сердечки и даты при каждом открытии */
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const hash = (s) => [...s].reduce((h, c) => Math.imul(h ^ c.charCodeAt(0), 16777619), 2166136261);

const cache = new Map();

/** Готовые ответы других участников на задание партнёра slug (без полей liked/mine — их добавляет mock.js) */
export function demoAnswers(slug) {
  if (cache.has(slug)) return cache.get(slug);
  const d = DEMO[slug];
  // Есть готовое задание с публикуемыми ответами (у викторины ответов не видно никому)
  const hasTask = Object.values(PARTNER_TASKS).some((t) => t.slug === slug && t.task && !t.hiddenAnswers);
  if (!d || !hasTask) return [];
  const r = rng(hash(slug));
  const now = Date.now();
  const list = Array.from({ length: d.count }, (_, i) => {
    const text = d.texts[i % d.texts.length];
    const a = {
      id: `${slug}-${i + 1}`,
      author: NAMES[Math.floor(r() * NAMES.length)],
      place: PLACES[Math.floor(r() * PLACES.length)],
      // Ответы за последние три недели, свежие чаще
      at: new Date(now - Math.floor(r() ** 1.6 * 21 * 86400000) - 3600000).toISOString(),
      // Несколько любимых ответов и длинный хвост с парой сердечек
      likes: Math.floor(r() ** 3.2 * 64),
      status: 'published',
    };
    if (text) a.text = text;
    const every = d.photoEvery ?? 1;
    if (d.photoSets && i % every === 0) a.photos = d.photoSets[Math.floor(i / every) % d.photoSets.length].map(PHOTO);
    // У ответа должно быть хоть что-то: пустой текст без фото — получает фото
    if (!a.text && !a.photos && d.photoSets) a.photos = d.photoSets[i % d.photoSets.length].map(PHOTO);
    return a;
  });
  cache.set(slug, list);
  return list;
}
