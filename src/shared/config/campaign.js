/** Задание партнёра и шаг, на котором оно открывается; у партнёра без задания (или задание ещё готовится) — null */
export function taskOfPartner(slug) {
  const step = CAMPAIGN.partnerStops.find((n) => PARTNER_TASKS[n]?.slug === slug);
  return step === undefined || !PARTNER_TASKS[step].task ? null : { step, ...PARTNER_TASKS[step] };
}
/** Готовое задание шага (с текстом) или null — «Скоро появится» */
